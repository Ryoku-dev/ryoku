package main

import (
	"fmt"
	"sort"
	"strings"

	wm "ryoku-wm"
)

// Keybind, unbind and rebind emission for the generated Hyprland config.

// hasProgram is the PATH lookup behind the catalogue's Needs rule; a test pins
// it so the rendered table never depends on what the box running it has.
var hasProgram = wm.HasProgram

func genKeybind(k Keybind) string {
	if strings.TrimSpace(k.Keys) == "" {
		return ""
	}
	var dsp string
	switch k.Action {
	case "exec", "":
		if strings.TrimSpace(k.Value) == "" {
			return ""
		}
		dsp = fmt.Sprintf("hl.dsp.exec_cmd(%s)", luaStr(k.Value))
	case "close":
		dsp = "hl.dsp.window.close()"
	case "fullscreen":
		dsp = "hl.dsp.window.fullscreen()"
	case "togglefloating":
		dsp = "hl.dsp.window.float({ action = \"toggle\" })"
	default:
		return ""
	}
	bind := func(keys string) string {
		if k.Release {
			return fmt.Sprintf("hl.bind(%s, %s, { release = true })\n", luaStr(keys), dsp)
		}
		return fmt.Sprintf("hl.bind(%s, %s)\n", luaStr(keys), dsp)
	}
	out := bind(k.Keys)
	// The number pad fires whichever way NumLock sits: a custom chord on a
	// KP_<digit> binds its NumLock-off twin to the same dispatcher too, the way
	// the shipped families cover both keypad faces. Unlike a rebind, a custom
	// bind is a direct hl.bind, so it can carry the extra line here.
	for _, twin := range wm.NumpadAliases(k.Keys) {
		out += bind(twin)
	}
	return out
}

// genUnbinds drops the shipped chords a config import must release so an imported
// bind that shadows a shipped one wins. Emitted before the binds, so after
// binds.lua registered the shipped chord and before the imported bind re-adds it.
func genUnbinds(o Overrides) string {
	var b strings.Builder
	for _, c := range o.Unbinds {
		if c = strings.TrimSpace(c); c == "" {
			continue
		}
		fmt.Fprintf(&b, "hl.unbind(%s)\n", luaStr(c))
	}
	return b.String()
}

// renderRebinds is the K() lookup binds.lua consults: one [default chord] =
// chosen chord per rebind or false for a switched-off bind. Always a full table
// so clearing the last override leaves no stale entry behind.
func renderRebinds(o Overrides) []byte {
	entries := make(map[string]string, len(o.KeybindRebinds)+len(o.KeybindDisabled))
	rebindKeys := make([]string, 0, len(o.KeybindRebinds))
	for k := range o.KeybindRebinds {
		rebindKeys = append(rebindKeys, k)
	}
	sort.Strings(rebindKeys)
	for _, rawFrom := range rebindKeys {
		from := strings.TrimSpace(rawFrom)
		to := strings.TrimSpace(o.KeybindRebinds[rawFrom])
		if from == "" || to == "" || from == to {
			continue
		}
		// A family rebind is stored as one {n} entry, but binds.lua binds each
		// member and both number-pad faces through its own K() lookup, so expand
		// the placeholder into the concrete per-member entries those lookups ask
		// for. FamilyRebind guards the value shape so a stray entry cannot map ten
		// workspace keys onto one chord.
		if eff, ok := wm.FamilyRebind(from, o.KeybindRebinds); ok {
			for n := 1; n <= 10; n++ {
				fromN, toN := wm.ExpandChord(from, n), wm.ExpandChord(eff, n)
				entries[fromN] = toN
				// The keypad sends a second keysym with NumLock off; binds.lua
				// looks that face up too, so a keypad family also maps the twin.
				fa, ta := wm.NumpadAliases(fromN), wm.NumpadAliases(toN)
				if len(fa) > 0 && len(ta) > 0 {
					entries[fa[0]] = ta[0]
				}
			}
			continue
		}
		entries[from] = to
	}

	// Disabled binds stay in the lookup with a false value, which lets K() stop
	// them before hl.bind sees them. Apply these after rebinds so switching off a
	// moved bind wins over both its family entry and a legacy per-member entry.
	for _, rawFrom := range o.KeybindDisabled {
		from := strings.TrimSpace(rawFrom)
		if from == "" {
			continue
		}
		if strings.Contains(from, "{n}") {
			for n := 1; n <= 10; n++ {
				fromN := wm.ExpandChord(from, n)
				entries[fromN] = ""
				for _, twin := range wm.NumpadAliases(fromN) {
					entries[twin] = ""
				}
			}
			continue
		}
		entries[from] = ""
	}

	// A bind whose program is not installed holds no chord either: the shipped
	// chord is the K() key, so the same false entry a switched-off bind gets
	// stops it before hl.bind, whatever the user moved it to.
	for _, b := range wm.ShippedBinds() {
		if b.Missing(hasProgram) != "" {
			entries[b.Chord] = ""
		}
	}

	keys := make([]string, 0, len(entries))
	for k := range entries {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var b strings.Builder
	b.WriteString("-- Generated by Ryoku Settings (Keyboard shortcuts page); change it in the GUI, not here.\nreturn {\n")
	for _, from := range keys {
		if to := entries[from]; to != "" {
			fmt.Fprintf(&b, "\t[%s] = %s,\n", luaStr(from), luaStr(to))
		} else {
			fmt.Fprintf(&b, "\t[%s] = false,\n", luaStr(from))
		}
	}
	b.WriteString("}\n")
	return []byte(b.String())
}

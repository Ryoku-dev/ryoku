import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const api = vm.createContext({});
vm.runInContext(fs.readFileSync(new URL('./phone.js', import.meta.url), 'utf8'), api);
assert.equal(api.device({ devices: [{ id: 'a', paired: true }, { id: 'b', paired: true }], activeDeviceId: 'b' }).id, 'b');
assert.equal(api.device({ devices: [{ id: 'a', paired: false }] }), null);
assert.equal(api.matches('AL Ice', ['Alice', 'mobile']), true);
assert.equal(api.matches('missing', ['Alice']), false);
assert.equal(api.numbers({ numbers: [{ number: '123' }, { number: '' }] }).join(','), '123');
let change = api.arrivals(null, {}, [{ id: 'old' }], false);
assert.equal(Object.keys(change.pending).length, 0);
change = api.arrivals(change.known, change.pending, [{ id: 'new' }], false);
assert.equal(Object.keys(change.pending).join(','), 'new');
change = api.arrivals(change.known, change.pending, [], false);
assert.equal(Object.keys(change.pending).join(','), 'new');
change = api.arrivals(change.known, change.pending, [{ id: 'seen' }], true);
assert.equal(Object.keys(change.pending).length, 0);
console.log('phone model tests passed');

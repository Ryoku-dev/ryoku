import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const S = require('./shortcuts.js');
const bind = { desc: 'Kit', hint: 'Press again to close', keys: ['Super', 'K'] };
for (const query of ['super+k', 'super k', 'Super+K', 'SUPER + K', 'kit', 'again'])
    assert.equal(S.matches(bind, query), true, query);
assert.equal(S.matches(bind, 'palette'), false);
assert.equal(S.matches(bind, 'fermer', s => s === bind.hint ? 'Appuyer pour fermer' : s), true);
assert.equal(S.matches({ desc: 'Réglages' }, 'reglages'), true);
assert.equal(S.chord(['Shift', 'Super', 'Ctrl', 'K']), S.chord('ctrl super shift k'));
assert.equal(S.chord('Meta+Return'), 'super+enter');
assert.equal(S.eventChord(75, 0x10000000, 'k'), 'super+k');
assert.equal(S.eventChord(0x01000021, 0x04000000, ''), '');
assert.equal(S.eventChord(0x01000030, 0, ''), 'f1');
assert.equal(S.eventChord(0x01000034, 0x04000000, ''), 'ctrl+f5');
const groups = S.groups([{ name: 'Shell', binds: [bind, { ...bind, disabled: true }, { desc: 'Pin', keys: ['Super', 'P'], unhonored: 'Not on niri' }] }, { name: 'niri', binds: [{ desc: 'Column', keys: ['Super', 'T'] }] }], '');
assert.equal(groups[0].rows.length, 2);
assert.equal(groups[1].name, 'niri');
const rows = groups.flatMap(g => g.rows);
assert.equal(S.find(rows, 'super+k'), 'c0b0');
assert.equal(S.find(rows, 'super+p'), '');
assert.equal(S.find(rows, 'super+t'), 'c1b0');
const blocks = S.layout(groups, 3, 29, 32, 10);
assert.deepEqual(blocks.map(b => [b.column, b.start, b.height]), [[0, 0, 90], [1, 2, 61]]);
assert.equal(S.groups([{ name: 'Shell', binds: [bind] }], 'unmatched').length, 0);
assert.equal(S.find([{ id: 'workspace', bind: { keys: ['Super', '1 … 0'] } }], 'super+7'), 'workspace');
assert.equal(S.find([{ id: 'keypad', bind: { keys: ['Super', 'Num 1 … 0'] } }], S.eventChord(0x37, 0x30000000, '7')), 'keypad');
assert.equal(S.find([{ id: 'volume', bind: { keys: ['Vol +'] } }], S.eventChord(0x01000072, 0, '')), 'volume');
console.log('Keys: chord, translated search, counts, provider rows, capture and layout passed');

type MCPServer struct {
	Name    string
	Command string
	Args    []string
	Env     map[string]string
	Type    string
	URL     string
	Headers map[string]string
}

// ImportReport says what a migration step brought over.
type ImportReport struct {
	Imported int
	Skipped  []string
	Notes    []string
}

// Gateway is the model router: chat completions plus the provider and key
// management behind the providers.*, models.list, models.probe and
// gateway.usage methods.
type Gateway interface {
	llm.Client
	Providers(ctx context.Context) ([]protocol.ProviderInfo, error)
	AddKey(ctx context.Context, p protocol.AddKeyParams) (protocol.ProviderInfo, error)
	RemoveKey(ctx context.Context, p protocol.RemoveKeyParams) (protocol.ProviderInfo, error)
	EnableProvider(ctx context.Context, p protocol.EnableProviderParams) (protocol.ProviderInfo, error)
	Test(ctx context.Context, provider string) (protocol.ProviderTestResult, error)
	// RefreshLimits reads account limits older than ten minutes in the
	// background, of one provider or every one, then reports the change
	// through the gateway's change hook.
	RefreshLimits(ctx context.Context, provider string) error
	// Models lists every chat model; Fresh reads the providers' own listings
	// again, each at most once a minute.
	Models(ctx context.Context, p protocol.ModelsParams) (protocol.ModelsResult, error)
	// Probe runs one small streamed request with a no-op tool on p.Model with
	// p.Options, so a Check proves the model answers and calls tools. A model
	// that does not answer or refuses an option is a result with OK false,
	// not an error.
	Probe(ctx context.Context, p protocol.ModelProbeParams) (protocol.ModelProbeResult, error)
	// Window is the context window in tokens of the model req would route to
	// first, 0 when unknown. It sends nothing; the engine sizes its output
	// budget and compaction with it before a request.
	Window(ctx context.Context, req llm.Request) int
	Usage(ctx context.Context, days int) (protocol.GatewayUsage, error)
	Status(ctx context.Context) protocol.GatewayStatus
	// API serves the router to other programs in OpenAI's shape, behind the
	// key APIKey returns (and replaces on rotate).
	API() http.Handler
	APIKey(ctx context.Context, rotate bool) (string, error)
	// ImportProwl copies keys for catalogue providers out of Prowl's state
	// directory. It is safe to call again: duplicates are skipped.
	ImportProwl(ctx context.Context, prowlDir string) (ImportReport, error)
	Close() error
}

// Local is Rashin's own llama.cpp: the model store, the downloads, the
// managed runtime and the llama-server router child, behind the local.*
// methods and the gateway's rashin-models provider. Nothing of it runs at
// rest: the router starts on the first request that needs it and stops after
// providers.models.idleMinutes.
type Local interface {
	// Models is the catalogue with what is installed and the runtime; it
	// starts nothing.
	Models(ctx context.Context) protocol.LocalResult
	// Devices queries the runtime on explicit UI request and caches by binary version.
	Devices(ctx context.Context) []protocol.LocalDevice
	// RuntimeState reads only current router process state.
	RuntimeState() (ready bool, address string)
	// Download starts or resumes a model's download; progress goes out as
	// local.progress.
	Download(ctx context.Context, id string) error
	// Cancel pauses a download, keeping its part files.
	Cancel(id string) error
	// Remove deletes a model's files, parts and manifest and unloads it.
	Remove(ctx context.Context, id string) (protocol.LocalResult, error)
	// Search lists a Hugging Face repo's GGUF files at its current revision.
	Search(ctx context.Context, repo string) (protocol.LocalSearchResult, error)
	// Add records a custom model pinned to its revision and starts its
	// download.
	Add(ctx context.Context, p protocol.LocalAddParams) (protocol.LocalModel, error)
	// InstallRuntime downloads the pinned upstream llama-server for backend
	// ("" for protocol.BackendVulkan); progress uses ID protocol.LocalRuntimeID.
	InstallRuntime(ctx context.Context, backend string) error
	// Start brings the router up, loading id when it is not empty.
	Start(ctx context.Context, id string) (protocol.LocalRuntime, error)
	// Stop ends the router at once; the next request starts it again.
	Stop()
	// Ensure is the gateway's one entry point: it starts the router when it
	// is down, loads model, and returns the base URL and bearer key a
	// request uses. A failure is a retryable attempt error for the router.
	Ensure(ctx context.Context, model string) (base, bearer string, err error)
	// Inventory is the installed models, read without any process or HTTP
	// call.
	Inventory() []protocol.LocalModel
	// Busy reports requests in flight, a start or a download, so the daemon
	// does not exit at idle.
	Busy() bool
	Close() error
}


// Package core holds the interfaces between the daemon and its subsystems, so
// the gateway, the engine, local models, the index and the self-improvement
// stores build and test on their own and the daemon wires concrete
// implementations together.
package core

import (
	"context"
	"encoding/json"
	"net/http"

	"ryoku-rashin/internal/llm"
	"ryoku-rashin/internal/protocol"
	"ryoku-rashin/internal/sandbox"
)

// Broadcaster sends a global event to every subscribed client.
type Broadcaster interface {
	Broadcast(event string, data any)
}

// Sink is how a runner reports a turn. The session manager implements it: Emit
// appends to the session log, coalescing text, thought and terminal deltas, and
// streams the result to attached clients.
type Sink interface {
	// Emit records one event. data is the protocol *Data type for kind.
	Emit(kind string, data any)
	// Update changes SessionInfo fields (model, mode, title, alive, state,
	// error) and broadcasts session.info.
	Update(func(*protocol.SessionInfo))
}

// PromptInput is one user turn.
type PromptInput struct {
	Turn int
	Text string
	// Goal marks a continuation or task turn generated by Rashin.
	Goal     bool
	Images   []protocol.Attachment
	Terminal *protocol.TerminalContext
	Handoff  *protocol.Handoff
	Origin   string
	// Run is a command the user runs in place of a question.
	Run string
	// History is the session log before this turn.
	History []protocol.SessionEvent
	Glance  *protocol.GlanceParams
}

// TurnResult is how a turn ended.
type TurnResult struct {
	Stop  string
	Usage *protocol.TokenUsage
}

// Runner drives one session. The session manager emits user, turn_start and
// turn_end; the runner emits everything in between. Prompt blocks until the
// turn ends. Calls on one runner are serialised by the session manager except
// Cancel and Permission, which may arrive while Prompt runs. A runner knows
// its model, modes and options without starting anything: the session
// manager has it emit them when the session is created.
type Runner interface {
	Prompt(ctx context.Context, in PromptInput, sink Sink) (TurnResult, error)
	// Cancel ends the running turn: it aborts the model stream, kills
	// foreground tool processes, and resolves open permissions as cancelled.
	Cancel()
	// Permission answers an open permission request.
	Permission(request, option string) error
	// SetModel checks model against the gateway's models, pins it and emits
	// model and that model's options.
	SetModel(ctx context.Context, model string, sink Sink) error
	// SetMode sets the session's approvals value (protocol.Approvals*).
	SetMode(ctx context.Context, mode string, sink Sink) error
	// SetOption sets one of the session's options, such as
	// protocol.OptionEffort or protocol.OptionPlan, to one of its choices.
	SetOption(ctx context.Context, option, value string, sink Sink) error
	// Alive reports whether something runs for this session between turns:
	// its tool host or a background terminal.
	Alive() bool
	// Stop ends what Alive reports; the session stays resumable.
	Stop() error
	// State is runner state persisted in the session's meta.json and handed
	// back on the next start. It carries its own version and a runner ignores
	// state it does not know, such as a former external harness's.
	State() json.RawMessage
}

// AskOptions creates an Ask runner.
type AskOptions struct {
	Session  protocol.SessionInfo
	Settings func() protocol.Settings
}

// Asker creates Ask runners.
type Asker interface {
	NewAsk(opts AskOptions) Runner
}

// AgentOptions creates an Agent runner. The model is Session.Model, which the
// session manager resolves before the runner exists ("" becomes agent.model).
type AgentOptions struct {
	Session  protocol.SessionInfo
	Settings func() protocol.Settings
	Cwd      string
	// Approvals is the session's mode: its team's approvals for a team
	// session, else agent.approvals, as the user last set it.
	Approvals func() string
	// Options are the session's options when it was created:
	// SessionNewParams.Options over agent.options, with protocol.OptionPlan
	// filled from agent.plan when neither names it.
	Options map[string]string
	// Brief is what the agent is told about where it runs: Ryoku, the vault,
	// Rashin and this session. It joins the system prompt, built once per
	// session.
	Brief func() string
	// Resume is the State a previous runner of this session returned.
	Resume json.RawMessage
	// Tools says which of Rashin's own in-process tools the session has.
	Tools ToolContext
	// MCP are the user's own MCP servers (protocol.FeatureMCP), whose tools
	// the engine's MCP client adds.
	MCP []MCPServer
	// Sandbox, set for a team session, is the sandbox every file and shell
	// tool of the session runs in, through one tool host child. Nil runs the
	// tools on the host as the user, gated by Approvals.
	Sandbox *sandbox.Spec
}

// ToolContext is what decides a session's Rashin tools: the session and its
// folder, whether it may use a screen and memory (Memory the memory tools,
// MemorySessions the search of past conversations), and the team task it
// works, nil outside one.
type ToolContext struct {
	Session        string
	Cwd            string
	Screen         bool
	Memory         bool
	MemorySessions bool
	Team           *TeamToolContext
}

// TeamToolContext is a team task's run as its team tools see it. Token is the
// run token Teams checks on every teams.agent_* call (protocol.AgentRef); Lead
// and Dream add the lead's and the dream manager's tools; SetupCards and
// Research are the team's optional features. Memory says the team remembers
// (Team.TeamMemory().Remember) and memory is on: the daemon sets
// ToolContext.Memory from it for team sessions, which never get
// MemorySessions.
type TeamToolContext struct {
	Team       string
	Task       string
	Member     string
	Token      string
	Lead       bool
	Dream      bool
	SetupCards bool
	Research   bool
	Memory     bool
}


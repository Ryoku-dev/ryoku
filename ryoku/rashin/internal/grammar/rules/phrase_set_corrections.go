// NewPhraseSetCorrectionsLintGroup produces a lint group that looks for errors in sets of common phrases.
func NewPhraseSetCorrectionsLintGroup() *lint.LintGroup {
	group := lint.NewLintGroup()
	for _, rule := range phraseSetCorrectionsOneToOne {
		group.AddChunkExprLinter(rule.name, NewMapPhraseSetLinterOneToOne(rule.pairs, rule.message, rule.description, &rule.kind))
	}
	for _, rule := range phraseSetCorrectionsManyToMany {
		group.AddChunkExprLinter(rule.name, NewMapPhraseSetLinterManyToMany(rule.pairs, rule.message, rule.description, &rule.kind))
	}
	enabled := true
	group.SetAllRulesTo(&enabled)
	return group
}


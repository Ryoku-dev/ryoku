package engine

import (
	"context"
	"encoding/json"

	"ryoku-rashin/internal/engine/tool"
	"ryoku-rashin/internal/llm"
	"ryoku-rashin/internal/protocol"
)

// The hooks below are how the optional self-improvement features plug into
// the engine without the engine importing them. The daemon registers the
// implementations in Deps; each implementation checks its own feature switch
// (protocol.Feature*) on every call, so a feature turned off costs nothing
// and needs no restart.

// TurnContext is what every hook is told about the turn it serves.
type TurnContext struct {
	Session protocol.SessionInfo
	Cwd     string
	// Project is the Git top level that holds Cwd, "" outside Git.
	Project string
	Profile tool.Profile
	// Prompt is the text given to the model for this turn.
	Prompt string
	// Goal marks a continuation or task turn generated by Rashin.
	Goal bool
}

// Well-known block names, in the order the system prompt places them.
const (
	BlockSkills    = "skills"
	BlockDecisions = "decisions"
	BlockRules     = "rules"
	BlockMemory    = "memory"
)

// Block is one section a ContextProvider adds to the system prompt. Text is
// the section body without a heading; Budget is the most bytes it may take,
// and the prompt builder cuts Text there (and drops blocks past the class's
// overall cap, last names first).
type Block struct {
	Name   string
	Text   string
	Budget int
}

// ContextProvider adds system-prompt blocks: skills, decisions, rules,
// memory. It is called once per turn, before the first model round. It must
// return the same Text while nothing it depends on changed, so the prompt
// prefix stays byte-stable for the llama.cpp prompt cache, and return nil
// when its feature is off or it has nothing for this session.
type ContextProvider interface {
	Blocks(ctx context.Context, tc TurnContext) []Block
}

// StreamGuards hands out one StreamGuard per turn: the TTSR stream rules
// that apply to the session. Nil means none apply.
type StreamGuards interface {
	Guard(tc TurnContext) StreamGuard
}

// StreamGuard watches one model reply as it streams. The engine calls
// Observe with every delta of an attempt, in order, and Reset before each
// new attempt (a retry, a recovery nudge, the round after a tool result).
// Observe is called from the turn's goroutine only.
type StreamGuard interface {
	// Observe returns an Interrupt when a rule fires, nil otherwise. For an
	// interrupting rule the engine aborts the stream, discards the partial
	// reply and retries the round with Message appended. A Notice lets the
	// reply go on. Observe returns at most one non-Notice Interrupt per
	// attempt, and any number of Notices.
	Observe(delta llm.Delta) *Interrupt
	Reset()
}

// Interrupt is a fired rule: its name and the note the model is told.
// Message is the complete wrapped note (`<system-interrupt ...>` or
// `<system-reminder ...>`); the engine appends it verbatim as a user
// message.
type Interrupt struct {
	Rule    string
	Message string
	// Notice delivers Message without aborting: the engine lets the reply
	// go on and appends Message as a user message after this round's tool
	// results, before the next model call; when the turn ends without
	// another round, it goes before the next turn's prompt.
	Notice bool
}

// TurnObserver learns from a finished turn: auto-learn capture, decision
// extraction, grievance flush. The engine calls it after the turn's last
// event, from its own goroutine, with a context that outlives the turn but
// ends at daemon shutdown; it never delays the next turn. An observer that
// does slow work (a model call) must do it in the background.
type TurnObserver interface {
	TurnEnded(ctx context.Context, rec TurnRecord)
}

// TurnRecord is one finished turn.
type TurnRecord struct {
	TurnContext
	Turn int
	// Calls are every tool call of the turn in order, subagents' included
	// (with Parent set).
	Calls []CallRecord
	// Text is the final assistant reply.
	Text string
	// Model is the provider/model that answered last.
	Model string
	// Stop is the protocol.Stop* the turn ended with.
	Stop  string
	Usage llm.Usage
}

// CallRecord is one tool call of a turn. Result is what the model was told,
// cut to a summary (at most 2 KiB).
type CallRecord struct {
	ID      string
	Name    string
	Args    json.RawMessage
	Result  string
	IsError bool
	Parent  string
}

// Judge answers a question about some text with a light model, its output
// constrained to schema (a JSON Schema object). Used by unexpected-stop
// detection (always on) and judged rules.
type Judge interface {
	Ask(ctx context.Context, question string, schema json.RawMessage) (Verdict, error)
}

// Verdict is a judge's answer: JSON matching the schema, and how sure the
// judge is of it, from 0 to 1 (token probability where the server reports
// it, else 1 for a schema-valid answer).
type Verdict struct {
	JSON        json.RawMessage
	Probability float64
}
